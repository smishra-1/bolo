import type { NativeLang, TargetLang } from "./languages";

type Term = { text: string; roman?: string };

type Concept = {
  id: string;
  emoji: string;
  difficulty: 1 | 2 | 3;
  gloss: Record<NativeLang, string>;
  terms: Record<TargetLang, Term>;
};

type Row = Record<TargetLang, [text: string, roman?: string]>;

/**
 * One row per word: [text, reading]. The reading is only given for languages
 * that are not written in Latin letters. The same word is both the answer when
 * the language is being learned and the prompt when it is the learner's own.
 */
function word(id: string, emoji: string, difficulty: 1 | 2 | 3, row: Row): Concept {
  const langs = Object.keys(row) as TargetLang[];
  return {
    id,
    emoji,
    difficulty,
    gloss: Object.fromEntries(langs.map((l) => [l, row[l][0]])) as Record<NativeLang, string>,
    terms: Object.fromEntries(langs.map((l) => [l, { text: row[l][0], ...(row[l][1] ? { roman: row[l][1] } : {}) }])) as Record<TargetLang, Term>,
  };
}

